/// <summary>
/// ビヘイビアツリーノードの実行結果（ステータス）を示す列挙型。
/// 各ノードは実行（Tick）されると、必ずこれらのいずれかを返す。
/// </summary>
public enum NodeStatus
{
    /// <summary>
    /// ノードの処理が正常に完了したことを示す。
    /// （例：目標地点に到達した、攻撃が当たった、条件を満たしている等）
    /// </summary>
    Success,

    /// <summary>
    /// ノードの処理が失敗したことを示す。
    /// （例：ターゲットが見つからない、移動経路がない、条件を満たしていない等）
    /// </summary>
    Failure,

    /// <summary>
    /// ノードの処理が現在進行中であることを示す。
    /// （例：移動中、攻撃アニメーションの再生中、待機中など）
    /// 次フレームでも継続してこのノードを評価すべきことを親ノードに伝える。
    /// </summary>
    Running
}
